async function main() {
  for (const g of groups) {
    await prisma.categoryGroup.upsert({
      where: { id: g.id },
      update: { name: g.name, order: g.order },
      create: { id: g.id, name: g.name, order: g.order },
    });
  }

  for (const cat of categories) {
    const data = {
      name: cat.name,
      icon: cat.icon,
      order: cat.order,
      visible: cat.visible,
      sellOnce: cat.sellOnce,
      groupId: cat.groupId,
      fields: JSON.stringify(cat.fields),
    };
    await prisma.category.upsert({
      where: { slug: cat.slug },
      update: data,
      create: { ...data, slug: cat.slug },
    });
  }
  console.log("Seeded " + groups.length + " groups and " + categories.length + " categories with hidden credential fields");
}

main().finally(() => prisma.$disconnect());
